import React from 'react';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import '@testing-library/jest-dom';
import axios from 'axios';
import Optimizer from './Optimizer';
jest.mock('axios', () => ({post: jest.fn()}));
const data = {usedTickers:['AAPL','MSFT','NVDA'],weights:{AAPL:.5,MSFT:.3,NVDA:.2},perStock:{AAPL:{beta:1.1,expectedCAPM:.08,cagrApprox:.09}},stats:{expected_return:.08,volatility:.2,sharpe:.3},baseline:{expected_return:.07,volatility:.19,sharpe:.26},market:{Rm:.1,Rf:.02}};
beforeEach(() => {axios.post.mockReset();axios.post.mockResolvedValue({data});});
test('date range request and equal-weight results remain intact', async () => {
 render(<Optimizer/>);
 fireEvent.change(screen.getByLabelText('Begin date'),{target:{value:'2020-01-01'}});
 fireEvent.change(screen.getByLabelText('End date'),{target:{value:'2024-01-01'}});
 fireEvent.click(screen.getByRole('button',{name:'Run optimizer'}));
 await screen.findByText('50.00%',{selector:'.number'});
 expect(axios.post.mock.calls[0][1]).toEqual({tickers:['AAPL','MSFT','NVDA'],mode:'max_sharpe',market:'US',targetReturn:null,startDate:'2020-01-01',endDate:'2024-01-01'});
 expect(screen.getByRole('columnheader',{name:'Equal weight'})).toBeInTheDocument();
 expect(screen.getByText('8.00%',{selector:'.estimate-table td'})).toBeInTheDocument();
});
test('market formatting, keyboard ticker entry, lookback and target payload',async()=>{
 render(<Optimizer/>);
 fireEvent.change(screen.getByLabelText('Portfolio market'),{target:{value:'HK'}});
 fireEvent.change(screen.getByLabelText('Add ticker'),{target:{value:'700'}});
 fireEvent.keyDown(screen.getByLabelText('Add ticker'),{key:'Enter'});
 expect(screen.getByRole('button',{name:'Remove 0700.HK'})).toBeInTheDocument();
 fireEvent.change(screen.getByLabelText('Optimization objective'),{target:{value:'target_return'}});
 fireEvent.change(screen.getByLabelText(/Target return \(decimal\)/),{target:{value:'0.15'}});
 fireEvent.click(screen.getByRole('button',{name:'Lookback',exact:true}));
 fireEvent.change(screen.getByLabelText('Lookback days'),{target:{value:'365'}});
 fireEvent.click(screen.getByRole('button',{name:'Run optimizer'}));
 await waitFor(()=>expect(axios.post).toHaveBeenCalled());
 const payload=axios.post.mock.calls[0][1];expect(payload).toMatchObject({tickers:['0700.HK'],market:'HK',mode:'target_return',targetReturn:.15,historyDays:365});expect(payload.startDate).toBeUndefined();
});
test('failed recalculation removes stale results and exposes an alert',async()=>{
 render(<Optimizer/>);fireEvent.click(screen.getByRole('button',{name:'Run optimizer'}));await screen.findByRole('columnheader',{name:'Equal weight'});
 axios.post.mockRejectedValueOnce({response:{data:{detail:'Insufficient history'}}});
 fireEvent.click(screen.getByRole('button',{name:'Run optimizer'}));
 expect(await screen.findByRole('alert')).toHaveTextContent('Insufficient history');
 expect(screen.queryByRole('columnheader',{name:'Equal weight'})).not.toBeInTheDocument();
 expect(screen.getByRole('button',{name:'Run optimizer'})).toBeEnabled();
});
